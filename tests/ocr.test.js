const assert = require('node:assert/strict');
const vm = require('node:vm');
const fs = require('node:fs');
const ctx = vm.createContext({ companySettings: () => ({}), pdfDate: () => null, round2: n => Math.round(n * 100) / 100 });
vm.runInContext(fs.readFileSync('src/part17.js', 'utf8'), ctx);
const parse = text => ctx.parseReceiptText('ร้านทดสอบ\n' + text);
(async () => {
  assert.equal(ctx.ocrNum('1.070.00'), 1070);
  assert.equal(ctx.ocrNum('1.234.567.89'), 1234567.89);
  assert.equal(ctx.ocrNum('1,070.00'), 1070);
  assert.equal(parse('Grand Total 1.070.00\nCash 2,000.00\nChange 930.00').total, 1070);
  assert.equal(parse('TOTAL 1070.00\nCASH TOTAL 2000.00').total, 1070);
  assert.equal(parse('SUBTOTAL 1200.00\nGrand Total 1070.00').total, 1070);
  assert.equal(parse('สินค้า 1 1070.00 1070.00\nเงินสด 2000.00\nเงินทอน 930.00').total, 1070);
  assert.equal(parse('เงินสด 2000.00\nเงินทอน 930.00').total, 0);
  const receipt = parse('สินค้า 1 1.000.00 1.000.00\nSubtotal 1.000.00\nVAT 7% 70.00\nGrand Total 1.070.00\nCash 2000.00');
  assert.equal(receipt.items[0].price, 1000);
  assert.equal(receipt.vatMode, 'exclusive');
  const fragment = (str,y,hasEOL=false) => ({str,transform:[1,0,0,1,0,y],hasEOL});
  assert.equal(ctx.ocrPdfText([fragment('ร้าน',100,true),fragment('TOTAL',80),fragment('1,070.00',80),fragment('Cash',60),fragment('2,000.00',60)]), 'ร้าน\nTOTAL 1,070.00\nCash 2,000.00');
  const original = {type:'image/png',name:'large.png'};
  assert.equal((await ctx.fileToImages(original)).images[0], original);
  let cleaned = 0, destroyed = 0, rendered = 0;
  ctx.document = {createElement: () => ({getContext: () => ({}), toBlob(cb,type) {assert.equal(type,'image/png');cb({page:rendered});}})};
  ctx.loadPdfJs = async () => ({getDocument: () => ({promise: Promise.resolve({numPages:5, destroy:async()=>destroyed++, getPage:async p=>({getViewport:()=>({width:1200,height:1600}),render:()=>{rendered++;return {promise:Promise.resolve()};},getTextContent:async()=>({items:p===4?[]:[fragment('page '+p+' native receipt text',100,true)]}),cleanup:()=>cleaned++})})})});
  const pdf = await ctx.fileToImages({type:'application/pdf',name:'mixed.pdf',arrayBuffer:async()=>new ArrayBuffer(0)});
  assert.equal(pdf.images.length,5); assert.equal(rendered,5); assert.equal(cleaned,5); assert.equal(destroyed,1);
  const scanned = [];
  ctx.tessRead = async images => {scanned.push(images[0].page);return 'scanned fourth page TOTAL 1070.00';};
  const full = await ctx.ocrReadText(pdf);
  assert.deepEqual(scanned,[4]); assert.ok(full.includes('page 5')); assert.ok(full.includes('scanned fourth'));
  let request;
  ctx.getSample = async()=>({limits:async()=>({images:{maxCount:2}}),json:async(prompt,options)=>{request={prompt,options};return {};}});
  pdf.pageTexts[4] += 'x'.repeat(6500) + ' LAST PAGE END';
  await ctx.ocrByClaude(pdf);
  assert.equal(request.options.images.length,2); assert.ok(request.prompt.includes('LAST PAGE END')); assert.ok(request.prompt.includes('scanned fourth'));
  ctx.document.createElement = () => ({toBlob:cb=>cb(null)});
  await assert.rejects(ctx.ocrCanvasBlob(ctx.document.createElement()), /แปลงรูป/);
  console.log('PASS OCR regression checks: money, totals, PDF lines, five pages, mixed scans, original image, Claude limits and encoding errors');
})().catch(e=>{console.error(e);process.exitCode=1;});
